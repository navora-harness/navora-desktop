export function searchUserGuide(query:string){
  const tokens=query.normalize('NFKC').trim().toLocaleLowerCase().split(/\s+/).filter(Boolean)
  return userGuide.filter(chapter=>{const text=[chapter.title,chapter.summary,...chapter.sections.flatMap(item=>[item.title,...item.paragraphs,...item.steps||[]])].join(' ').normalize('NFKC').toLocaleLowerCase();return tokens.every(token=>text.includes(token))})
}

export const GUIDE_READING_STORAGE_KEY='navora.guide.reading'
export type GuideReading={version:1;chapter:string;positions:Record<string,number>}
/** Storage and deep links are data, never unchecked chapter/section identities. */
export function readGuideReading(raw:string|null|undefined):GuideReading{
  const fallback=():GuideReading=>({version:1,chapter:userGuide[0]!.id,positions:{}})
  try{
    const value:unknown=JSON.parse(raw||'null')
    if(!value||typeof value!=='object'||Array.isArray(value))return fallback()
    const saved=value as Record<string,unknown>
    if(saved.version!==undefined&&saved.version!==1)return fallback()
    const chapter=userGuide.some(item=>item.id===saved.chapter)?String(saved.chapter):userGuide[0]!.id
    const positions:Record<string,number>={}
    if(saved.positions&&typeof saved.positions==='object'&&!Array.isArray(saved.positions))for(const [id,top]of Object.entries(saved.positions))if(userGuide.some(item=>item.id===id)&&typeof top==='number'&&Number.isFinite(top)&&top>=0)positions[id]=Math.min(top,10_000_000)
    return {version:1,chapter,positions}
  }catch{return fallback()}
}
export function resolveGuideTarget(chapter:unknown,section?:unknown):{chapter:string;section?:string}{
  const selected=userGuide.find(item=>item.id===chapter)||userGuide[0]!
  return {chapter:selected.id,...(typeof section==='string'&&selected.sections.some(item=>item.id===section)?{section}:{})}
}
